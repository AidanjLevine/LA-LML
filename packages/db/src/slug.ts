/** URL-safe slug: "Zebulon & Friends!" -> "zebulon-and-friends", "Café" -> "cafe", "McCabe's" -> "mccabes". */
export function slugify(value: string): string {
  return value
    .normalize("NFKD")
    .replace(/[̀-ͯ]/g, "")
    .toLowerCase()
    .replace(/&/g, " and ")
    .replace(/['’]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-+|-+$/g, "");
}
